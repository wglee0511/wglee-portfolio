function haversineKm(lat: number, lng: number): number {
  const rad = Math.PI / 180;
  const dLat = (lat - ORIGIN.lat) * rad;
  const dLng = (lng - ORIGIN.lng) * rad;
  const a = Math.sin(dLat / 2) ** 2 + Math.cos(ORIGIN.lat * rad) * Math.cos(lat * rad) * Math.sin(dLng / 2) ** 2;
  return 6371 * 2 * Math.asin(Math.sqrt(a));
}

/** 지역 문자열("서울 강남구", "원격 (서울 금천구)" 등)의 고양시 일산까지 직선거리(km). 모르는 지역은 Infinity. */
export function distanceFromGoyangKm(region: string): number {
  const hit = CENTERS.find(([name]) => region.includes(name));
  return hit ? haversineKm(hit[1], hit[2]) : Infinity;
}

/** 정렬용 비교: Infinity끼리도 안전하게 같다고 본다. */
export function compareDistance(a: number, b: number): number {
  return a === b ? 0 : a < b ? -1 : 1;
}
